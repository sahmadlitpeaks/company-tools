import AxeBuilder from "@axe-core/playwright";
import { expect, test } from "@playwright/test";
import { noOverflow } from "./projects-fixtures";

test.skip(process.env.PM_STACK_E2E !== "1", "Requires disposable migrated local PostgreSQL stack");

test("decisions persist with real cookies, PostgreSQL and separate proposer and approver", async ({ page, baseURL }) => {
  test.setTimeout(90_000);
  expect(new URL(baseURL!).hostname).toMatch(/^(localhost|127\.0\.0\.1)$/);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const email = process.env.E2E_EMAIL ?? "admin@agholding.net";
  const password = process.env.E2E_PASSWORD;
  expect(password, "Set a local test admin password").toBeTruthy();
  expect((await page.request.post("/api/auth/login", { data: { email, password } })).status()).toBe(200);
  const key = `DC${Math.random().toString(36).slice(2, 8).toUpperCase()}`;
  const projectResponse = await page.request.post("/api/pm/projects", { data: { key, name: `${key} decisions`, sprints_enabled: false } });
  expect(projectResponse.status()).toBe(201);
  const project = await projectResponse.json();
  const reviewerEmail = `${key.toLowerCase()}-reviewer@agholding.net`;
  const reviewerName = `${key} Reviewer`;
  const reviewerResponse = await page.request.post("/api/users", { data: { email: reviewerEmail, display_name: reviewerName, password: "ReviewerOld123!", role: "member", status: "active" } });
  expect(reviewerResponse.status()).toBe(201);
  const reviewer = await reviewerResponse.json();
  expect((await page.request.post(`/api/pm/projects/${project.id}/members`, { data: { user_id: reviewer.id, role: "viewer" } })).status()).toBe(201);
  const issueResponse = await page.request.post(`/api/pm/projects/${project.id}/issues`, { data: { summary: "Implement finance review", issue_type: "story" } });
  expect(issueResponse.status()).toBe(201);
  const issue = await issueResponse.json();
  await page.goto(`/projects/${key}?tab=decisions`);
  await expect(page.getByText("No decisions found", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Create decision", exact: true }).click();
  const form = page.getByRole("dialog", { name: "Create decision", exact: true });
  await form.getByLabel("Title", { exact: true }).fill("Finance review for large purchases");
  await form.getByLabel("Context / problem").fill("Purchases need an agreed approval threshold.");
  await form.getByLabel("Chosen approach").fill("Finance reviews purchases above 5000.");
  await form.getByLabel("Rationale", { exact: true }).fill("Keep small purchases fast.");
  await form.getByRole("combobox", { name: "Approver", exact: true }).click();
  await page.getByRole("option", { name: reviewerName, exact: true }).click();
  await form.getByRole("checkbox", { name: new RegExp(issue.key) }).check();
  await form.getByRole("button", { name: "Add reference" }).click();
  await form.getByLabel("Reference 1 description").fill("Finance meeting notes");
  await form.getByLabel("Reference 1 URL").fill("https://example.test/finance-notes");
  await form.getByRole("button", { name: "Save draft", exact: true }).click();
  const detail = page.getByRole("dialog", { name: "Finance review for large purchases", exact: true });
  await expect(detail.getByText("Draft", { exact: true })).toBeVisible();
  const id = new URL(page.url()).searchParams.get("decision")!;
  await detail.getByRole("button", { name: "Submit for approval", exact: true }).click();
  const submit = page.getByRole("dialog", { name: "Submit for approval", exact: true });
  await submit.getByLabel("Summary of this submission").fill("Initial finance policy");
  await submit.getByRole("button", { name: "Submit for approval", exact: true }).click();
  await expect(detail.getByText("Pending approval", { exact: true })).toBeVisible();
  const pending = await (await page.request.get(`/api/pm/decisions/${id}`)).json();
  expect(pending.revisions[0].snapshot.issues[0].key).toBe(issue.key);
  expect(pending.revisions[0].snapshot.evidence[0].label).toBe("Finance meeting notes");
  expect((await page.request.patch(`/api/pm/issues/${issue.id}`, { data: { summary: "Changed after decision submission" } })).status()).toBe(200);
  await page.request.post("/api/auth/logout");
  expect((await page.request.post("/api/auth/login", { data: { email: reviewerEmail, password: "ReviewerOld123!" } })).status()).toBe(200);
  expect((await page.request.post("/api/auth/change-password", { data: { current_password: "ReviewerOld123!", new_password: "ReviewerNew123!" } })).status()).toBe(200);
  await page.reload();
  await expect(detail.getByRole("button", { name: "Edit draft" })).toHaveCount(0);
  await expect(detail.getByRole("link", { name: `${issue.key} · Implement finance review`, exact: true })).toBeVisible();
  await expect(detail.getByText("Changed after decision submission", { exact: true })).toHaveCount(0);
  await detail.getByRole("button", { name: "Approve revision 1", exact: true }).click();
  const approval = page.getByRole("dialog", { name: "Approve revision", exact: true });
  await approval.getByLabel("Approval note (optional)").fill("Approved by finance.");
  await approval.getByRole("button", { name: "Approve revision", exact: true }).click();
  await expect(detail.getByText("Approved", { exact: true })).toBeVisible();
  await page.reload();
  await expect(detail.getByText("Approved by finance.", { exact: true })).toBeVisible();
  const approved = await (await page.request.get(`/api/pm/decisions/${id}`)).json();
  expect(approved.approved_revision_number).toBe(1);
  expect(approved.revisions[0].snapshot).toEqual(pending.revisions[0].snapshot);
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await noOverflow(page);
  await page.screenshot({ path: `test-results/decisions-live-approved-${page.viewportSize()!.width}.png`, fullPage: true });
  await page.request.post("/api/auth/logout");
  expect((await page.request.post("/api/auth/login", { data: { email, password } })).status()).toBe(200);
  const extraResponse = await page.request.post(`/api/pm/projects/${project.id}/issues`, { data: { summary: "Implement the approved threshold", issue_type: "task" } });
  expect(extraResponse.status()).toBe(201);
  const extra = await extraResponse.json();
  await page.reload();
  await detail.getByRole("button", { name: "Manage issue links", exact: true }).click();
  const manage = page.getByRole("dialog", { name: "Manage issue links", exact: true });
  await manage.getByRole("combobox", { name: "Issue", exact: true }).click();
  await page.getByRole("option", { name: `${extra.key} · Implement the approved threshold`, exact: true }).click();
  await manage.getByRole("combobox", { name: "Relationship", exact: true }).click();
  await page.getByRole("option", { name: "Implements", exact: true }).click();
  await manage.getByRole("button", { name: "Link issue", exact: true }).click();
  await expect(manage.getByText("Linked issues (2/100)", { exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await noOverflow(page);
  await manage.getByRole("button", { name: "Done", exact: true }).click();
  await page.reload();
  const tracked = await (await page.request.get(`/api/pm/decisions/${id}`)).json();
  expect(tracked.status).toBe("approved");
  expect(tracked.approved_at).toBe(approved.approved_at);
  expect(tracked.revisions).toEqual(approved.revisions);
  expect(tracked.issues.find((i: { id: string }) => i.id === extra.id).relationship).toBe("implements");
  expect((await (await page.request.get(`/api/pm/issues/${extra.id}/decisions`)).json()).map((row: { id: string }) => row.id)).toContain(id);
  await detail.getByRole("button", { name: "Manage issue links", exact: true }).click();
  await manage.getByRole("button", { name: `Unlink ${extra.key}`, exact: true }).click();
  await expect(manage.getByText("Linked issues (1/100)", { exact: true })).toBeVisible();
  await manage.getByRole("button", { name: "Done", exact: true }).click();
  expect(await (await page.request.get(`/api/pm/issues/${extra.id}/decisions`)).json()).toEqual([]);
  await detail.getByRole("button", { name: "Propose a revision" }).click();
  const revise = page.getByRole("dialog", { name: "Return to draft", exact: true });
  await revise.getByLabel("Reason", { exact: true }).fill("Review a higher threshold.");
  await revise.getByRole("button", { name: "Return to draft", exact: true }).click();
  await detail.getByRole("button", { name: "Edit draft" }).click();
  const edit = page.getByRole("dialog", { name: `Edit ${approved.key}`, exact: true });
  await edit.getByLabel("Chosen approach").fill("Finance reviews purchases above 10000.");
  await edit.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(detail.getByText("Finance reviews purchases above 10000.", { exact: true })).toBeVisible();
  await detail.getByRole("button", { name: "View approved version", exact: true }).click();
  await expect(detail.getByText("Finance reviews purchases above 5000.", { exact: true })).toBeVisible();
  const changed = await (await page.request.get(`/api/pm/decisions/${id}`)).json();
  expect(changed.status).toBe("draft");
  expect(changed.approved_revision_number).toBe(1);
  expect(changed.revisions[0].snapshot).toEqual(pending.revisions[0].snapshot);
  const links = await (await page.request.get(`/api/pm/issues/${issue.id}/decisions`)).json();
  expect(links.map((row: { id: string }) => row.id)).toContain(id);
  await detail.getByRole("button", { name: "Close", exact: true }).click();
  await page.getByRole("button", { name: "Toggle dark mode" }).click();
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark");
  await page.goto(`/projects/${key}?tab=decisions&decision=${id}`);
  await expect(detail.getByText("Draft", { exact: true })).toBeVisible();
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([]);
  await noOverflow(page);
  expect(errors).toEqual([]);
});
